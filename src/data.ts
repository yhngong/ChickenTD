export function getWaveDefinition(waveNumber: number): WaveDefinition {
  if (waveNumber >= 1 && waveNumber <= HANDCRAFTED_WAVES.length) {
    return HANDCRAFTED_WAVES[waveNumber - 1];
  }
  const extra = waveNumber - HANDCRAFTED_WAVES.length;
  const alphaCount = 1 + Math.floor(extra / 2);
  const kitsuneCount = 2 + extra;
  const timberCount = 4 + extra * 2;
  return {
    waveNumber,
    title: `Freeplay Rampage #${waveNumber}`,
    callout: `Endless Foxes (${alphaCount} Mega Alpha, ${kitsuneCount} Kitsunes) with +${
      extra * 18
    }% HP!`,
    groups: [
      { enemyType: 'fox_timber', count: timberCount, intervalSec: Math.max(0.9, 2.2 - extra * 0.1), startDelaySec: 0.3 },
      { enemyType: 'fox_kitsune', count: kitsuneCount, intervalSec: Math.max(1.4, 3.8 - extra * 0.15), startDelaySec: 3.0 },
      { enemyType: 'fox_alpha', count: alphaCount, intervalSec: Math.max(2.5, 6.0 - extra * 0.2), startDelaySec: 6.0 },
    ],
  };
}
